/**
 * Token build — DTCG JSON → CSS custom properties, TypeScript, JSON.
 *
 * Layers (each only references the layer below it):
 *   tokens/primitive/   palette — raw values, never emitted as CSS
 *   tokens/semantic/    mode-independent: font, space, radius, border, motion, opacity, layer
 *   tokens/themes/<mode>/  mode-dependent: color, elevation (surfaces + shadows)
 *   tokens/variants/<name>/{shared,light,dark}/  optional overrides → [data-rovo-variant="<name>"]
 *
 * Naming mirrors the Atlassian Design System: foundation.property.modifier
 *   color.background.brand.bold.hovered  →  --ds-background-brand-bold-hovered
 *   elevation.shadow.raised              →  --ds-shadow-raised
 *   space.200                            →  --ds-space-200
 * ("color" and "elevation" are dropped from CSS names exactly as ADS does, so components
 *  written against this system also run on real @atlaskit/tokens.)
 */
import StyleDictionary from 'style-dictionary';
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const T = (...p) => path.join(ROOT, 'tokens', ...p);
const OUT = path.join(ROOT, 'dist');
const PREFIX = 'ds';
const MODES = ['light', 'dark'];

// Groups whose $extensions mark every child as a Rovo DS extension (DTCG doesn't inherit $extensions).
const EXTENSION_GROUPS = /^(motion\.rovo|layer|breakpoint)\./;
const DROP_FOUNDATION = new Set(['color', 'elevation']);
const cleanPath = (p) => p.filter((s) => s !== '[default]');
const dotName = (p) => cleanPath(p).join('.');
const cssName = (p) => {
  const parts = cleanPath(p);
  if (DROP_FOUNDATION.has(parts[0])) parts.shift();
  return `--${PREFIX}-${parts.join('-')}`;
};

StyleDictionary.registerTransform({
  name: 'name/ads',
  type: 'name',
  transform: (token) => cssName(token.path),
});

const TRANSFORMS = [
  'attribute/cti',
  'name/ads',
  'fontFamily/css',
  'cubicBezier/css',
  'typography/css/shorthand',
  'shadow/css/shorthand',
  'color/css',
];

const exists = (p) => fs.existsSync(p);
const globIf = (dir) => (exists(dir) ? [path.join(dir, '**/*.json')] : []);

async function resolve(sources) {
  const sd = new StyleDictionary({
    source: sources,
    usesDtcg: true,
    log: { warnings: 'disabled', verbosity: 'silent' },
    platforms: { css: { transforms: TRANSFORMS } },
  });
  const { allTokens } = await sd.getPlatformTokens('css');
  const map = new Map();
  for (const t of allTokens) {
    if (t.path[0] === 'palette') continue; // primitives stay private
    map.set(dotName(t.path), {
      name: dotName(t.path),
      cssVar: t.name,
      type: t.$type ?? t.type,
      value: t.$value ?? t.value,
      description: t.$description ?? t.description ?? '',
      extension: Boolean(t.$extensions?.['rovo-ds'] ?? t.original?.$extensions?.['rovo-ds']) || EXTENSION_GROUPS.test(dotName(t.path)),
    });
  }
  return map;
}

const baseSources = (mode, variant) => [
  T('primitive/**/*.json'),
  T('semantic/**/*.json'),
  T(`themes/${mode}/**/*.json`),
  ...(variant ? [...globIf(T('variants', variant, 'shared')), ...globIf(T('variants', variant, mode))] : []),
];

const isModeToken = (name) => name.startsWith('color.') || name.startsWith('elevation.');
const decl = (tokens, indent = '  ') =>
  tokens.map((t) => `${indent}${t.cssVar}: ${t.value};`).join('\n');

// ---------------------------------------------------------------- base build
const base = {};
for (const mode of MODES) base[mode] = await resolve(baseSources(mode));

const shared = [...base.light.values()].filter((t) => !isModeToken(t.name) && !t.name.startsWith('breakpoint.'));
const modeTokens = (mode) => [...base[mode].values()].filter((t) => isModeToken(t.name));

const reducedMotion = shared
  .filter((t) => t.type === 'duration')
  .map((t) => ({ ...t, value: '0ms' }));

let css = `/* Rovo DS tokens — generated by scripts/build-tokens.mjs. Do not edit. */

/* Mode-independent: font, space, radius, border, motion, opacity, layer */
:root {
${decl(shared)}
}

/* Light (default) */
:root,
[data-color-mode="light"] {
  color-scheme: light;
${decl(modeTokens('light'))}
}

/* Dark */
[data-color-mode="dark"] {
  color-scheme: dark;
${decl(modeTokens('dark'))}
}

/* Auto: follow the OS */
@media (prefers-color-scheme: dark) {
  [data-color-mode="auto"] {
    color-scheme: dark;
${decl(modeTokens('dark'), '    ')}
  }
}

/* Reduced motion: every duration collapses to instant. Components also guard loops. */
@media (prefers-reduced-motion: reduce) {
  :root {
${decl(reducedMotion, '    ')}
  }
}
`;

// ------------------------------------------------------------ variant builds
// A variant only emits the tokens it changes. Put data-rovo-variant on the same
// element as data-color-mode (usually <html>).
const variantsDir = T('variants');
const variants = exists(variantsDir)
  ? fs.readdirSync(variantsDir).filter((d) => fs.statSync(path.join(variantsDir, d)).isDirectory())
  : [];
const variantManifest = [];

for (const v of variants) {
  const vr = {};
  for (const mode of MODES) vr[mode] = await resolve(baseSources(mode, v));
  const diff = (mode, pred) =>
    [...vr[mode].values()].filter((t) => pred(t) && base[mode].get(t.name)?.value !== t.value);

  const sharedDiff = diff('light', (t) => !isModeToken(t.name));
  const lightDiff = diff('light', (t) => isModeToken(t.name));
  // In dark, re-declare anything changed in either mode so light overrides never leak into dark.
  const touched = new Set([...lightDiff, ...diff('dark', (t) => isModeToken(t.name))].map((t) => t.name));
  const darkDecl = [...touched].map((n) => vr.dark.get(n));
  const sel = `[data-rovo-variant="${v}"]`;

  css += `
/* Variant: ${v} */
${sel} {
${decl([...sharedDiff, ...lightDiff])}
}
${sel}[data-color-mode="dark"] {
${decl(darkDecl)}
}
@media (prefers-color-scheme: dark) {
  ${sel}[data-color-mode="auto"] {
${decl(darkDecl, '    ')}
  }
}
`;
  variantManifest.push({ name: v, changed: sharedDiff.length + touched.size });
}

// ----------------------------------------------------------------- write out
fs.mkdirSync(path.join(OUT, 'css'), { recursive: true });
fs.mkdirSync(path.join(OUT, 'js'), { recursive: true });
fs.mkdirSync(path.join(OUT, 'json'), { recursive: true });
fs.writeFileSync(path.join(OUT, 'css', 'tokens.css'), css);

const all = [...base.light.values()].map((t) => ({
  name: t.name,
  cssVar: t.cssVar,
  type: t.type,
  description: t.description,
  extension: t.extension,
  light: t.value,
  dark: base.dark.get(t.name)?.value ?? t.value,
}));
fs.writeFileSync(path.join(OUT, 'json', 'tokens.json'), JSON.stringify({ tokens: all, variants: variantManifest }, null, 2));

const nameMap = Object.fromEntries(all.map((t) => [t.name, t.cssVar]));
const lightMap = Object.fromEntries(all.map((t) => [t.name, String(t.light)]));
const ts = `/* Generated by scripts/build-tokens.mjs. Do not edit. */
export const tokenNames = ${JSON.stringify(nameMap, null, 2)} as const;

export type TokenName = keyof typeof tokenNames;

/** Light-mode resolved values, used as CSS fallbacks. */
export const lightValues: Record<TokenName, string> = ${JSON.stringify(lightMap, null, 2)};

/**
 * Reference a design token from TS/JSX, mirroring @atlaskit/tokens' token():
 *   style={{ color: token('color.text.subtle') }}  →  "var(--ds-text-subtle, #505258)"
 */
export function token(name: TokenName, fallback: string = lightValues[name]): string {
  return \`var(\${tokenNames[name]}, \${fallback})\`;
}

export const breakpoints = {
${all.filter((t) => t.name.startsWith('breakpoint.')).map((t) => `  ${t.name.split('.')[1]}: '${t.light}',`).join('\n')}
} as const;

export const variants = ${JSON.stringify(variantManifest.map((v) => v.name))} as const;
`;
fs.writeFileSync(path.join(OUT, 'js', 'tokens.ts'), ts);

console.log(
  `✓ ${all.length} tokens (${shared.length} shared, ${modeTokens('light').length} per mode)` +
    (variants.length ? `, variants: ${variants.join(', ')}` : '') +
    ` → dist/css/tokens.css, dist/js/tokens.ts, dist/json/tokens.json`,
);
